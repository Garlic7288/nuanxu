"""从 NuanXu/Program.cs 原文抽出 ShowQrPreview，生成可直接编译的 Extracted.cs。

不手抄方法体，避免「测试的是副本、线上跑的是另一份」。
"""
import io
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "..", "NuanXu", "Program.cs")
DST = os.path.join(HERE, "Extracted.cs")

text = io.open(SRC, encoding="utf-8-sig").read()
start = text.index("private static void ShowQrPreview(Image image)")
# 按大括号配平找方法结尾
i = text.index("{", start)
depth = 0
for j in range(i, len(text)):
    if text[j] == "{":
        depth += 1
    elif text[j] == "}":
        depth -= 1
        if depth == 0:
            end = j + 1
            break
body = text[start:end]

out = """// <auto-generated> 由 extract.py 从 NuanXu/Program.cs 抽出，请勿手改 </auto-generated>
using System.Drawing;
using System.Windows.Forms;

namespace QrPreviewAudit;

internal static class Extracted
{
    public static void Run(Image image) => ShowQrPreview(image);

%s
}
""" % body

io.open(DST, "w", encoding="utf-8", newline="\n").write(out)
print("extracted %d chars -> %s" % (len(body), DST))
