"""从 NuanXu/Program.cs 原文抽出 NormalizeReminderText 与 MaxReminderTextLength，
生成 TextTruncationAudit/Generated.cs，供审计程序调用。

为什么不手抄一份：手抄的方法和产品代码会漂移，测过了不代表线上那版是对的。
这里直接按源码抽，方法体一个字都不改（只把 private 改成 internal 好让同程序集调用）。

用法：python extract.py   （在 tools/TextTruncationAudit 下运行，或从仓库根运行）
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SRC = os.path.join(ROOT, "NuanXu", "Program.cs")
OUT = os.path.join(HERE, "Generated.cs")

SIG = "private static string NormalizeReminderText(string? text)"


def extract_method(text: str) -> str:
    i = text.find(SIG)
    if i < 0:
        raise SystemExit(f"在 Program.cs 里找不到方法签名：{SIG}")

    brace = text.find("{", i)
    if brace < 0:
        raise SystemExit("方法签名后找不到左大括号")

    depth = 0
    for j in range(brace, len(text)):
        c = text[j]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return text[i : j + 1]
    raise SystemExit("大括号没有配对，抽取失败")


def main() -> int:
    text = open(SRC, encoding="utf-8").read()

    m = re.search(r"internal const int MaxReminderTextLength = (\d+);", text)
    if not m:
        raise SystemExit("找不到 MaxReminderTextLength 常量")
    limit = m.group(1)

    method = extract_method(text).replace(
        SIG, "internal static string NormalizeReminderText(string? text)"
    )

    generated = (
        "// <auto-generated>由 extract.py 从 NuanXu/Program.cs 抽取，不要手改</auto-generated>\n"
        "// 方法签名带 string?，需要显式打开 nullable 上下文，否则 CS8669\n"
        "#nullable enable\n"
        "using System.Globalization;\n"
        "\n"
        "namespace TextTruncationAudit;\n"
        "\n"
        "internal static class Truncate\n"
        "{\n"
        f"    internal const int MaxReminderTextLength = {limit};\n"
        "\n"
        + "\n".join("    " + line if line.strip() else line for line in method.splitlines())
        + "\n}\n"
    )

    with open(OUT, "w", encoding="utf-8") as f:
        f.write(generated)

    print(f"已生成 {OUT}")
    print(f"  MaxReminderTextLength = {limit}")
    print(f"  方法体 {len(method.splitlines())} 行")
    return 0


if __name__ == "__main__":
    sys.exit(main())
